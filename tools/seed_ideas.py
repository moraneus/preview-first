def main():
    g = json.load(open(GRAPH, encoding="utf-8"))
    ids = {n["id"] for n in g["nodes"]}
    sites = {n["url"].rstrip("/").replace("https://www.","https://"): n["id"] for n in g["nodes"] if n["kind"] == "reference-site"}
    added = 0
    for slug, name, cat, hook, what, impl, risk, note, seen, styles in SEED:
        nid = "idea." + slug
        if nid in ids:
            continue
        node = {"id": nid, "kind": "idea", "name": name, "category": cat, "what": what, "implementation": impl,
                "ai_tell_risk": risk, "ai_tell_note": note, "seen_on": seen, "renders": hook,
                "first_seen_year": 2024, "source": SRC, "added": TODAY, "last_verified": TODAY, "confidence": 0.75}
        g["nodes"].append(node); ids.add(nid); added += 1
        ev = [sites[u.rstrip("/").replace("https://www.","https://")] for u in seen if u.rstrip("/").replace("https://www.","https://") in sites]
        for st in styles:
            g["edges"].append({"from": nid, "to": "style." + st, "kind": "pairs_with", "weight": 0.8, "evidence": ev})
    for st, lst in STYLE_DEFAULTS.items():
        node = next(n for n in g["nodes"] if n["id"] == "style." + st)
        node["ideas"] = ["idea." + x for x in lst]
    json.dump(g, open(GRAPH, "w", encoding="utf-8"), indent=1, ensure_ascii=False); open(GRAPH, "a").write("\n")
    print("added", added, "ideas; nodes", len(g["nodes"]))

if __name__ == "__main__":
    main()
